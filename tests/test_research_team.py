"""Small synthetic kit fixtures, never a delivered research release or three-machine receipt."""
import importlib.util
import json
import os
from pathlib import Path
import sys
import subprocess
import tempfile
import unittest
from unittest.mock import patch
import zipfile

import pyarrow as pa
import pyarrow.parquet as pq

ROOT=Path(__file__).resolve().parents[1]
def module(name,path):
    spec=importlib.util.spec_from_file_location(name,path);m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m
fixture=module("research_team_fixture",ROOT/"tests/test_research_collection_loader.py")
packager=module("research_team_pack",ROOT/"scripts/pack-research-team.py")
v=packager.v


class ResearchTeamTest(unittest.TestCase):
    def setUp(self):
        self.temp=tempfile.TemporaryDirectory();self.addCleanup(self.temp.cleanup);self.root=Path(self.temp.name).resolve()
        self.inputs={}
        for index,split in enumerate(v.SPLITS,1):
            bundle=self.root/split;bundle.mkdir();pilot=self.root/(split+"-pilot");pilot.mkdir()
            fixture.fixture(bundle,pilot)
            dataset="ds_"+str(index)*64
            for file in bundle.glob("shard_*/*.parquet"):
                table=pq.read_table(file);field=table.schema.field("dataset_id")
                table=table.set_column(table.schema.get_field_index("dataset_id"),field,pa.array([dataset]*table.num_rows,type=field.type))
                pq.write_table(table,file)
            manifest=json.loads((bundle/"dataset_manifest.json").read_bytes());plan=manifest["collection_plan"]
            manifest.update(dataset_id=dataset,dataset_split=split,physical_gold_table_name="iceberg.dat03_catalog_"+"a"*32+".event_current",
                            gold_publication_id="pub_"+"b"*64,publication_bundle_sha256="b"*64,gold_snapshot_id="9007199254740993")
            plan.update(dataset_id=dataset,collection_id="col_"+str(index)*64,plan_sha256=str(index)*64)
            plan["coverage"]["required_month_count"]=225 if split=="REPRODUCTION" else 63
            fixture.write_json(bundle/"dataset_manifest.json",manifest)
            fixture.write_json(bundle/"collection-preparation.json",{"status":"RESEARCH_COLLECTION_PREPARED","plan":plan})
            pins=fixture.reindex(bundle);self.inputs[split]={"directory":bundle,**pins}
        self.output=self.root/"team.zip"

    def packed(self):
        with patch.object(packager.shutil,"disk_usage",return_value=type("Disk",(),{"free":32*1024**3})()):
            return packager.pack(self.inputs,self.output)

    def unpack(self):
        self.kit=self.root/"kit";self.kit.mkdir()
        # Trusted archive generated by this test, not arbitrary/user archive extraction.
        with zipfile.ZipFile(self.output) as archive:archive.extractall(self.kit)

    def test_same_release_is_deterministic_and_both_splits_verify_offline(self):
        result=self.packed();again=self.packed();self.assertTrue(again["reused"])
        self.assertEqual(result["zip_sha256"],again["zip_sha256"]);self.unpack()
        receipt=self.root/"recipient.json"
        verified=v.verify(self.kit,result["handoff_sha256"],"HoaiTam",receipt)
        self.assertEqual("TEAM_RESEARCH_VERIFIED",verified["status"]);self.assertTrue(verified["all_shards_verified"])
        self.assertEqual(set(v.SPLITS),set(verified["collections"]));self.assertTrue(receipt.is_file())
        self.assertFalse(verified["scientific_approval"]);self.assertFalse((self.root/"rosy179-receipt.json").exists())
        self.assertEqual(8,sum(r["feature_row_count"] for r in verified["collections"].values()))

    def test_wrong_external_input_pin_never_creates_zip(self):
        self.inputs["REPRODUCTION"]["manifest_sha256"]="f"*64
        with self.assertRaisesRegex(ValueError,"EXTERNAL_PIN_MISMATCH"):self.packed()
        self.assertFalse(self.output.exists())

    def test_delivered_verifier_runs_in_a_fresh_process_without_repository_imports(self):
        result=self.packed();self.unpack();receipt=self.root/"fresh-recipient.json"
        checked=subprocess.run([sys.executable,str(self.kit/"verify_dataset.py"),"--expected-handoff-sha256",result["handoff_sha256"],
                                "--recipient","HoaiTam","--receipt",str(receipt)],cwd=self.kit,
                               env={**os.environ,"PYTHONPATH":"","PYTHONDONTWRITEBYTECODE":"1"},capture_output=True,text=True,timeout=30)
        self.assertEqual(0,checked.returncode,checked.stderr)
        self.assertEqual("TEAM_RESEARCH_VERIFIED",json.loads(checked.stdout)["status"])
        self.assertFalse((self.kit/"__verified_no_cache__").exists())

    def test_ambient_modules_are_not_used_and_caller_state_is_restored(self):
        result=self.packed();self.unpack();prior_path=list(sys.path)
        poison=object()
        with patch.dict(sys.modules,{"experiment_harness":poison,"pilot_bundle":poison}):
            checked=v.verify(self.kit,result["handoff_sha256"],"HoaiTam")
            self.assertEqual("TEAM_RESEARCH_VERIFIED",checked["status"])
            self.assertIs(poison,sys.modules["experiment_harness"]);self.assertIs(poison,sys.modules["pilot_bundle"])
        self.assertEqual(prior_path,sys.path)

    def test_different_gold_snapshot_cannot_be_a_paired_release(self):
        bundle=self.inputs["EXTENSION"]["directory"]
        manifest=json.loads((bundle/"dataset_manifest.json").read_bytes());manifest["gold_snapshot_id"]="9007199254740997"
        fixture.write_json(bundle/"dataset_manifest.json",manifest);self.inputs["EXTENSION"].update(fixture.reindex(bundle))
        with self.assertRaisesRegex(ValueError,"GOLD_PIN_CHANGED"):self.packed()
        self.assertFalse(self.output.exists())

    def test_changed_shipped_code_is_rejected_before_import(self):
        result=self.packed();self.unpack();(self.kit/"tools/research_collection.py").write_text("raise AssertionError('never execute')")
        with self.assertRaisesRegex(ValueError,"FILE_CHANGED"):v.verify(self.kit,result["handoff_sha256"],"HoaiTam")

    def test_extra_file_or_symlink_never_passes(self):
        result=self.packed();self.unpack();extra=self.kit/"foreign.txt";extra.write_text("extra")
        with self.assertRaisesRegex(ValueError,"EXACT_FILE_SET"):v.verify(self.kit,result["handoff_sha256"],"HoaiTam")
        extra.unlink();(self.kit/"alias").symlink_to(self.root,target_is_directory=True)
        with self.assertRaisesRegex(ValueError,"UNSAFE_PATH"):v.verify(self.kit,result["handoff_sha256"],"HoaiTam")

    def test_existing_other_zip_is_not_overwritten(self):
        self.output.write_bytes(b"preserve-existing")
        with self.assertRaisesRegex(ValueError,"NO_OVERWRITE"):self.packed()
        self.assertEqual(b"preserve-existing",self.output.read_bytes())

    def test_source_change_after_semantic_validation_is_not_rehashed_as_valid(self):
        original=packager.v.summary
        def changed(collection):
            result=original(collection)
            if collection.manifest["dataset_split"]=="EXTENSION":
                (collection.root/"shard_00000/features.parquet").write_bytes(b"changed")
            return result
        with patch.object(packager.v,"summary",side_effect=changed):
            with self.assertRaisesRegex(ValueError,"SOURCE_CHANGED_DURING_PACK"):self.packed()
        self.assertFalse(self.output.exists())

    def test_low_host_disk_blocks_pack_before_output(self):
        with patch.object(packager.shutil,"disk_usage",return_value=type("Disk",(),{"free":1})()):
            with self.assertRaisesRegex(ValueError,"PHYSICAL_DISK_RESERVE"):packager.pack(self.inputs,self.output)
        self.assertFalse(self.output.exists())

    def test_receipt_must_be_outside_kit_and_cannot_overwrite(self):
        result=self.packed();self.unpack()
        with self.assertRaisesRegex(ValueError,"RECEIPT_OUTSIDE_KIT"):v.verify(self.kit,result["handoff_sha256"],"HoaiTam",self.kit/"receipt.json")
        receipt=self.root/"existing.json";receipt.write_text("preserve")
        with self.assertRaises(FileExistsError):v.verify(self.kit,result["handoff_sha256"],"HoaiTam",receipt)
        self.assertEqual("preserve",receipt.read_text())


if __name__=="__main__":unittest.main()
